const COMMENT_MINUTE_OFFSETS = [4, 12, 27, 53, 91, 148, 232, 347, 512, 733, 1014, 1295, 1540, 1817, 2175] as const;

function addMinutes(value: string, minutes: number) {
  return new Date(Date.parse(value) + minutes * 60_000).toISOString();
}

function makeComments(postIndex: number): EditorialComment[] {
  const post = POST_SEEDS[postIndex];
  const stances = COMMENT_STANCES[postIndex];
  return post.comments.map((body, commentIndex) => {
    const stance = stances[commentIndex] === "A" ? "agree" : "caution";
    const offset = COMMENT_MINUTE_OFFSETS[commentIndex] + ((postIndex * 5 + commentIndex) % 7);
    return {
      id: `daily-0820-${postIndex + 1}-${commentIndex + 1}-${stance}`,
      displayName: post.names[commentIndex],
      body,
      createdAt: addMinutes(post.createdAt, offset),
    };
  });
}

export const august20EditorialPosts: EditorialPost[] = POST_SEEDS.map(({ comments: _comments, names: _names, ...post }) => post);

const COMMENTS = new Map<string, EditorialComment[]>(
  august20EditorialPosts.map((post, postIndex) => [post.id, makeComments(postIndex)]),
);

export function august20EditorialComments(postId: string) {
  return COMMENTS.get(postId) ?? [];
}

