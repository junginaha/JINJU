const COMMENT_STANCES = [
  "ACACACACAC",
  "CAACACCAACAC",
  "ACAACCACCAACA",
  "CACACACACACACA",
  "AACACCAACCACACA",
  "CACACCAACA",
  "ACCAACACCAACAC",
  "CAACACCAACACACA",
  "CAACACACCA",
  "ACCACACACCA",
  "ACAACCAACCA",
  "CAACCACACACA",
  "AACCAACACACCA",
] as const;

const COMMENT_MINUTE_OFFSETS = [6, 15, 31, 58, 94, 143, 219, 326, 488, 701, 953, 1238, 1511, 1834, 2167] as const;

function addMinutes(value: string, minutes: number) {
  return new Date(Date.parse(value) + minutes * 60_000).toISOString();
}

function makeComments(postIndex: number): EditorialComment[] {
  const post = POST_SEEDS[postIndex];
  const stances = COMMENT_STANCES[postIndex];
  return post.comments.map((body, commentIndex) => {
    const stance = stances[commentIndex] === "A" ? "agree" : "caution";
    const offset = COMMENT_MINUTE_OFFSETS[commentIndex] + ((postIndex * 3 + commentIndex) % 9);
    return {
      id: `daily-0821-${postIndex + 1}-${commentIndex + 1}-${stance}`,
      displayName: post.names[commentIndex],
      body,
      createdAt: addMinutes(post.createdAt, offset),
    };
  });
}

export const august21EditorialPosts: EditorialPost[] = POST_SEEDS.map(({ comments: _comments, names: _names, ...post }) => post);

const COMMENTS = new Map<string, EditorialComment[]>(
  august21EditorialPosts.map((post, postIndex) => [post.id, makeComments(postIndex)]),
);

export function august21EditorialComments(postId: string) {
  return COMMENTS.get(postId) ?? [];
}

assertEditorialDiversity(august21EditorialPosts, august21EditorialComments);
