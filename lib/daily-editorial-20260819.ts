function addMinutes(value: string, minutes: number) {
  return new Date(Date.parse(value) + minutes * 60_000).toISOString();
}

function commentDisplayName(postIndex: number, commentIndex: number) {
  return `${NAME_PREFIXES[commentIndex]} ${NAME_SUFFIXES[(postIndex + commentIndex) % NAME_SUFFIXES.length]}`;
}

function makeComments(postIndex: number): EditorialComment[] {
  const post = POST_SEEDS[postIndex];
  const stances = COMMENT_STANCES[postIndex];
  return post.comments.map((body, commentIndex) => {
    const stance = stances[commentIndex] === "A" ? "agree" : "caution";
    const offset = COMMENT_MINUTE_OFFSETS[commentIndex] + ((postIndex * 3 + commentIndex) % 7);
    return {
      id: `daily-0819-${postIndex + 1}-${commentIndex + 1}-${stance}`,
      displayName: commentDisplayName(postIndex, commentIndex),
      body,
      createdAt: addMinutes(post.createdAt, offset),
    };
  });
}

export const august19EditorialPosts: EditorialPost[] = POST_SEEDS.map(({ comments: _comments, ...post }) => post);

const COMMENTS = new Map<string, EditorialComment[]>(
  august19EditorialPosts.map((post, postIndex) => [post.id, makeComments(postIndex)]),
);

export function august19EditorialComments(postId: string) {
  return COMMENTS.get(postId) ?? [];
}

assertEditorialDiversity(august19EditorialPosts, august19EditorialComments);
