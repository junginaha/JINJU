const COMMENT_STANCES = [
  "ACACACACAC",
  "CAACACCAACA",
  "ACACCACCA",
  "CAACACCAAC",
  "ACCAACACACC",
  "CACAACCACACA",
  "AACACCAACC",
  "CAACCACAACA",
  "CACACACAC",
  "ACAACCACACCA",
] as const;

const COMMENT_MINUTE_OFFSETS = [5, 11, 17, 34, 63, 108, 181, 296, 472, 728, 1037, 1486] as const;

function addMinutes(value: string, minutes: number) {
  return new Date(Date.parse(value) + minutes * 60_000).toISOString();
}

function makeComments(postIndex: number): EditorialComment[] {
  const post = POST_SEEDS[postIndex];
  const stances = COMMENT_STANCES[postIndex];
  return post.comments.map((body, commentIndex) => {
    const stance = stances[commentIndex] === "A" ? "agree" : "caution";
    return {
      id: `daily-0825-${postIndex + 1}-${commentIndex + 1}-${stance}`,
      displayName: post.names[commentIndex],
      body,
      createdAt: addMinutes(post.createdAt, COMMENT_MINUTE_OFFSETS[commentIndex]),
    };
  });
}

export const august25EditorialPosts: EditorialPost[] = POST_SEEDS.map(({ comments: _comments, names: _names, ...post }) => post);

const COMMENTS = new Map<string, EditorialComment[]>();
for (const [postIndex, post] of august25EditorialPosts.entries()) {
  COMMENTS.set(post.id, makeComments(postIndex));
}

export function august25EditorialComments(postId: string) {
  return COMMENTS.get(postId) ?? [];
}

assertEditorialDiversity(august25EditorialPosts, august25EditorialComments);
