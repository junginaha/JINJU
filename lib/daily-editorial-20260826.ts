const COMMENT_MINUTE_OFFSETS = [4, 10, 16, 31, 58, 97, 164, 251, 389, 621, 953, 1518] as const;

function addMinutes(value: string, minutes: number) {
  return new Date(Date.parse(value) + minutes * 60_000).toISOString();
}

function makeComments(postIndex: number): EditorialComment[] {
  const post = POST_SEEDS[postIndex];
  const stances = COMMENT_STANCES[postIndex];
  return post.comments.map((body, commentIndex) => ({
    id: `daily-0826-${postIndex + 1}-${commentIndex + 1}-${stances[commentIndex] === "A" ? "agree" : "caution"}`,
    displayName: post.names[commentIndex],
    body,
    createdAt: addMinutes(post.createdAt, COMMENT_MINUTE_OFFSETS[commentIndex]),
  }));
}

export const august26EditorialPosts: EditorialPost[] = POST_SEEDS.map(({ comments: _comments, names: _names, ...post }) => post);

const COMMENTS = new Map<string, EditorialComment[]>();
for (const [postIndex, post] of august26EditorialPosts.entries()) COMMENTS.set(post.id, makeComments(postIndex));

export function august26EditorialComments(postId: string) {
  return COMMENTS.get(postId) ?? [];
}

