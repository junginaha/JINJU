function commentName(globalIndex: number) {
  const prefix = COMMENT_NAME_PREFIXES[Math.floor(globalIndex / COMMENT_NAME_ROLES.length) % COMMENT_NAME_PREFIXES.length];
  return `${prefix} ${COMMENT_NAME_ROLES[globalIndex % COMMENT_NAME_ROLES.length]}`;
}

