const COMMENT_MINUTE_OFFSETS = [5, 14, 29, 52, 87, 131, 198, 291, 423, 607, 821, 1086, 1374, 1703, 2059] as const;

function addMinutes(value: string, minutes: number) {
  return new Date(Date.parse(value) + minutes * 60_000).toISOString();
}

function makeComments(postIndex: number, globalStart: number): EditorialComment[] {
  const post = POST_SEEDS[postIndex];
  const stances = COMMENT_STANCES[postIndex];
  return post.comments.map((body, commentIndex) => {
    const stance = stances[commentIndex] === "A" ? "agree" : "caution";
    const offset = COMMENT_MINUTE_OFFSETS[commentIndex] + ((postIndex * 5) % 11);
    return {
      id: `daily-0822-${postIndex + 1}-${commentIndex + 1}-${stance}`,
      displayName: commentName(globalStart + commentIndex),
      body,
      createdAt: addMinutes(post.createdAt, offset),
    };
  });
}

