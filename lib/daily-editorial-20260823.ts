export const august23EditorialPosts: EditorialPost[] = POST_SEEDS.map(({ comments: _comments, ...post }) => post);

let globalCommentIndex = 0;
const COMMENTS = new Map<string, EditorialComment[]>();
for (const [postIndex, post] of august23EditorialPosts.entries()) {
  const comments = makeComments(postIndex, globalCommentIndex);
  COMMENTS.set(post.id, comments);
  globalCommentIndex += comments.length;
}

export function august23EditorialComments(postId: string) {
  return COMMENTS.get(postId) ?? [];
}

